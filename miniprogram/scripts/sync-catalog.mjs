// 从官网同步门店/课程字典与图片，保证两端业务编码一致。
// 用法：在 miniprogram/ 目录执行 node scripts/sync-catalog.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { venues } from '../../website/src/data/site.js'
import { programs } from '../../website/src/data/programs.js'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const webRoot = path.resolve(root, '..', 'website')
const sourceDir = path.join(webRoot, 'public', 'images')
const targetDir = path.join(root, 'assets', 'images')
fs.mkdirSync(targetDir, { recursive: true })

const programImages = {
  P01: 'program-boxing',
  P02: 'program-conditioning',
  P03: 'program-strength',
  P04: 'program-rope',
  P05: 'program-mobility',
  P06: 'program-recovery',
}

const venueImages = {
  'V-01': 'station-tianhe',
  'V-02': 'station-haizhu',
  'V-03': 'station-panyu',
}

const coachImages = {
  'coach-01': 'coach-01',
  'coach-02': 'coach-02',
  'coach-03': 'coach-03',
}

function copyIfPresent(sourceName, targetName) {
  const source = path.join(sourceDir, sourceName)
  const target = path.join(targetDir, targetName)
  if (!fs.existsSync(source)) {
    if (fs.existsSync(target)) return true
    console.warn(`missing source image: ${sourceName}`)
    return false
  }
  fs.copyFileSync(source, target)
  return true
}

const catalogPrograms = programs.map((program) => {
  const file = programImages[program.no]
  const image = file ? `/assets/images/${file}.webp` : ''
  if (file) copyIfPresent(`${file}-960.webp`, `${file}.webp`)
  return { ...program, image, imageUrl: image }
})

const catalogVenues = venues.map((venue) => ({
  ...venue,
  imageUrl: venueImages[venue.code] ? `/assets/images/${venueImages[venue.code]}.webp` : '',
}))

for (const [source, target] of Object.entries(coachImages)) {
  copyIfPresent(`${source}-960.webp`, `${target}.webp`)
}

const payload = {
  generatedAt: new Date().toISOString(),
  venues: catalogVenues,
  programs: catalogPrograms,
}

const banner = `// AUTO-GENERATED by scripts/sync-catalog.mjs — 数据源：website/src/data/*.js
// 请勿手工编辑；官网数据变更后重新执行 node scripts/sync-catalog.mjs
`

fs.writeFileSync(
  path.join(root, 'data', 'catalog.js'),
  `${banner}module.exports = ${JSON.stringify(payload, null, 2)}\n`,
)

console.log(`catalog synced: ${catalogPrograms.length} programs, ${catalogVenues.length} venues`)
